import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, copyFileSync, chmodSync, symlinkSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const temp = mkdtempSync(join(tmpdir(), 'validator-script-test-'));
try {
  const root = join(temp, 'project');
  const bin = join(temp, 'bin');
  mkdirSync(join(root, 'scripts'), { recursive: true });
  mkdirSync(join(root, 'programs/mini-amm/src'), { recursive: true });
  mkdirSync(join(root, 'target/deploy'), { recursive: true });
  mkdirSync(bin);
  copyFileSync(resolve('scripts/localValidator.sh'), join(root, 'scripts/localValidator.sh'));
  const id = 'DnW4iMWC5gCjPZkk2kkdTrY5uybW3w6r6aLdS6meynMn';
  writeFileSync(join(root, 'programs/mini-amm/src/lib.rs'), `declare_id!("${id}");\n`);
  writeFileSync(join(bin, 'solana'), '#!/bin/sh\nprintf "%s\\n" "${FAKE_GENESIS:-5eykt4UsFv8P8NJdTREpY1vzqKqZKvdp}"\n');
  writeFileSync(join(bin, 'solana-test-validator'), '#!/bin/sh\nprintf "%s\\n" "$@" > "$CAPTURE_ARGS"\n');
  chmodSync(join(bin, 'solana'), 0o755);
  chmodSync(join(bin, 'solana-test-validator'), 0o755);
  const script = join(root, 'scripts/localValidator.sh');
  const argsFile = join(temp, 'args');
  const env: NodeJS.ProcessEnv = { ...process.env, PATH: `${bin}:${process.env.PATH}`, CAPTURE_ARGS: argsFile };
  delete env.LOCAL_VALIDATOR_MAINNET_RPC;
  execFileSync('bash', ['-n', script]);
  let result = spawnSync('bash', [script], { env, encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /anchor build/);
  writeFileSync(join(root, 'target/deploy/mini_amm.so'), 'mock');
  result = spawnSync('bash', [script], { env: { ...env, FAKE_GENESIS: 'not-mainnet' }, encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /bukan mainnet/);
  result = spawnSync('bash', [script], { env, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  const args = readFileSync(argsFile, 'utf8').trim().split('\n');
  const at = (flag: string) => args[args.indexOf(flag) + 1];
  assert.equal(at('--url'), 'https://api.mainnet-beta.solana.com');
  assert.equal(at('--ledger'), join(root, '.local-validator/ledger'));
  assert(args.includes('--reset'));
  assert.equal(at('--bind-address'), '127.0.0.1');
  assert.equal(at('--clone'), 'So11111111111111111111111111111111111111112');
  assert.equal(at('--clone-upgradeable-program'), 'TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb');
  assert.equal(at('--bpf-program'), id);
  assert.equal(args[args.indexOf('--bpf-program') + 2], join(root, 'target/deploy/mini_amm.so'));
  rmSync(join(root, '.local-validator'), { recursive: true });
  symlinkSync(temp, join(root, '.local-validator'));
  result = spawnSync('bash', [script], { env, encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /symlink/);
  console.log('LOCAL VALIDATOR SCRIPT TESTS PASSED!');
} finally {
  rmSync(temp, { recursive: true, force: true });
}
